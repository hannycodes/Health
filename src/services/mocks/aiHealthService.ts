function matchRule(text: string, hasImage: boolean): AssistantRule {
  const lower = text.toLowerCase();
  const matched = RULES.find((rule) =>
    rule.keywords.some((keyword) => lower.includes(keyword)),
  );

  if (matched) {
    // With an image but no usable keyword, route to dermatology instead of
    // claiming the image alone identifies anything.
    return matched;
  }
  if (hasImage) {
    return RULES.find((rule) => rule.specialty === "Dermatology") ?? FALLBACK;
  }
  return FALLBACK;
}

function buildReply(input: AIHealthRequest, hasImage: boolean): AIHealthResponse {
  const text = input.message.trim();
  const lower = text.toLowerCase();
  const isEmergency = EMERGENCY_PATTERNS.some((pattern) => lower.includes(pattern));
  const rule = matchRule(text, hasImage);

  const { patientContext } = input;
  const contextNotes: string[] = [];
  if (patientContext.age !== undefined) {
    contextNotes.push(`Your profile lists your age as ${patientContext.age}.`);
  }
  if (patientContext.allergies?.length) {
    contextNotes.push(
      `Your profile lists allergies: ${patientContext.allergies.join(", ")}. Mention these to the clinician.`,
    );
  }
  if (patientContext.conditions?.length) {
    contextNotes.push(
      `Existing conditions on file: ${patientContext.conditions.join(", ")}.`,
    );
  }
  if (patientContext.medications?.length) {
    contextNotes.push(
      `Current medications on file: ${patientContext.medications.join(", ")}.`,
    );
  }

  if (isEmergency) {
    const message = [
      "What you described may be a medical emergency.",
      "Call your local emergency number or go to the nearest emergency department now. Do not wait for an appointment.",
      hasImage
        ? "An image cannot confirm or rule out an emergency."
        : "",
      contextNotes.join(" "),
    ]
      .filter(Boolean)
      .join("\n\n");

    return {
      conversationId: "",
      message,
      urgency: "EMERGENCY",
      recommendations: [
        "Call emergency services or go to the nearest emergency department now.",
        "Do not drive yourself if you feel faint.",
      ],
      followUpQuestions: [],
      disclaimer: MOCK_DISCLAIMER,
      recommendedDoctorIds: [],
      recommendedHospitalIds: [],
      isMock: true,
    };
  }

  const db = demoDb.get();
  const doctors = db.doctors.filter(
    (doctor) => doctor.specialty === rule.specialty && doctor.isAcceptingPatients,
  );
  const hospitalIds = Array.from(new Set(doctors.map((doctor) => doctor.hospitalId)));

  const message = [
    `Summary: ${rule.summary}`,
    rule.guidance,
    hasImage
      ? "Your image was attached for a clinician to review. An image alone cannot confirm a condition."
      : "",
    contextNotes.join(" "),
    "This is general information to help you decide what to do next, not a diagnosis.",
  ]
    .filter(Boolean)
    .join("\n\n");

  return {
    conversationId: "",
    message,
    urgency: rule.urgency,
    recommendations: rule.recommendations,
    followUpQuestions: rule.followUps,
    disclaimer: MOCK_DISCLAIMER,
    recommendedDoctorIds: doctors.map((doctor) => doctor.id),
    recommendedHospitalIds: hospitalIds,
    isMock: true,
  };
}

function toAttachment(image: UploadedImage): AIChatAttachment {
  return {
    id: image.id,
    fileName: image.fileName,
    mimeType: image.mimeType,
    sizeBytes: image.sizeBytes,
    previewUrl: image.previewUrl,
  };
}

/** Persist metadata only: blob previews never reach localStorage. */
function persistable(message: AIChatMessage): AIChatMessage {
  return {
    ...message,
    attachments: message.attachments.map((attachment) => ({
      ...attachment,
      previewUrl: "",
    })),
  };
}

function hydrate(message: AIChatMessage): AIChatMessage {
  return {
    ...message,
    attachments: message.attachments.map((attachment) => ({
      ...attachment,
      previewUrl: uploadedImages.get(attachment.id)?.previewUrl ?? "",
    })),
  };
}

function cloneConversation(conversation: AIConversation): AIConversation {
  return {
    ...conversation,
    messages: conversation.messages.map((message) => hydrate({ ...message })),
  };
}

function titleFrom(message: string) {
  const trimmed = message.trim().replace(/\s+/g, " ");
  if (!trimmed) return "Image consultation";
  return trimmed.length > 60 ? `${trimmed.slice(0, 57)}…` : trimmed;
}

export class MockAIHealthService implements AIHealthService {
  listConversations(patientId: string): Promise<AIConversation[]> {
    return respond(() =>
      demoDb
        .get()
        .conversations.filter((conversation) => conversation.patientId === patientId)
        .slice()
        .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
        .map(cloneConversation),
    );
  }

  getConversation(conversationId: string): Promise<AIConversation | null> {
    return respond(() => {
      const conversation = demoDb
        .get()
        .conversations.find((item) => item.id === conversationId);
      return conversation ? cloneConversation(conversation) : null;
    });
  }

  startConversation(patientId: string): Promise<AIConversation> {
    return respond(() => {
      const now = new Date().toISOString();
      const conversation: AIConversation = {
        id: createId("cnv"),
        patientId,
        title: "New conversation",
        createdAt: now,
        updatedAt: now,
        messages: [],
      };
      demoDb.mutate((db) => {
        db.conversations = [conversation, ...db.conversations];
      });
      return cloneConversation(conversation);
    });
  }

  uploadImage(file: File): Promise<UploadedImage> {
    return respond(() => {
      if (!ACCEPTED_IMAGE_TYPES.includes(file.type)) {
        throw new ApiError({
          status: 415,
          message: "Upload a JPG, PNG or WebP image.",
        });
      }
      if (file.size > MAX_IMAGE_BYTES) {
        throw new ApiError({
          status: 413,
          message: `Images must be smaller than ${Math.round(MAX_IMAGE_BYTES / (1024 * 1024))} MB.`,
        });
      }

      const previewUrl =
        typeof URL !== "undefined" && typeof URL.createObjectURL === "function"
          ? URL.createObjectURL(file)
          : "";

      const uploaded: UploadedImage = {
        id: createId("img"),
        fileName: file.name,
        mimeType: file.type,
        sizeBytes: file.size,
        previewUrl,
      };

      uploadedImages.set(uploaded.id, uploaded);
      return uploaded;
    }, 400);
  }

  sendMessage(input: AIHealthRequest): Promise<AIHealthResponse> {
    return respond(() => {
      const message = input.message.trim();
      if (!message && !input.imageIds?.length) {
        throw new ApiError({
          status: 422,
          message: "Describe your symptoms or attach an image before sending.",
        });
      }

      const attachments = (input.imageIds ?? []).map((id) => {
        const image = uploadedImages.get(id);
        if (!image) {
          throw new ApiError({
            status: 400,
            message: "That image reference is no longer available. Please attach it again.",
          });
        }
        return toAttachment(image);
      });

      let conversation = input.conversationId
        ? demoDb.get().conversations.find((item) => item.id === input.conversationId)
        : undefined;

      if (input.conversationId && !conversation) {
        throw new ApiError({
          status: 404,
          message: "This conversation is no longer available.",
        });
      }
      if (conversation && conversation.patientId !== input.patientId) {
        throw new ApiError({
          status: 403,
          message: "You do not have access to this conversation.",
        });
      }

      const now = new Date().toISOString();
      if (!conversation) {
        conversation = {
          id: createId("cnv"),
          patientId: input.patientId,
          title: titleFrom(message),
          createdAt: now,
          updatedAt: now,
          messages: [],
        };
      }

      const reply = buildReply(input, attachments.length > 0);
      const conversationId = conversation.id;

      const patientMessage: AIChatMessage = {
        id: createId("msg"),
        conversationId,
        role: "PATIENT",
        content: message,
        attachments,
        isMock: false,
        createdAt: now,
      };

      const assistantMessage: AIChatMessage = {
        id: createId("msg"),
        conversationId,
        role: "ASSISTANT",
        content: reply.message,
        attachments: [],
        urgency: reply.urgency,
        followUpQuestions: reply.followUpQuestions,
        recommendations: reply.recommendations,
        disclaimer: reply.disclaimer,
        recommendedDoctorIds: reply.recommendedDoctorIds,
        recommendedHospitalIds: reply.recommendedHospitalIds,
        isMock: true,
        createdAt: new Date().toISOString(),
      };

      const target = conversation;
      demoDb.mutate((db) => {
        const existing = db.conversations.find((item) => item.id === conversationId);
        if (existing) {
          existing.messages = [
            ...existing.messages,
            persistable(patientMessage),
            persistable(assistantMessage),
          ];
          existing.updatedAt = assistantMessage.createdAt;
          if (existing.messages.length <= 2) {
            existing.title = titleFrom(message);
          }
        } else {
          db.conversations = [
            {
              ...target,
              messages: [persistable(patientMessage), persistable(assistantMessage)],
              updatedAt: assistantMessage.createdAt,
            },
            ...db.conversations,
          ];
        }
      });

      return { ...reply, conversationId };
    }, 750);
  }
}
