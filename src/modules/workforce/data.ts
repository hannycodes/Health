export function createWorkforceSeed(): WorkforceState {
  const accounts = professionals.map((person) => ({
    professionalId: person.id,
    email: person.email,
    password: SEEDED_WORKFORCE_PASSWORD,
  }));

  return {
    professionals: structuredClone(professionals),
    accounts,
    employers: structuredClone(employers),
    opportunities: structuredClone(opportunities),
    applications: structuredClone(applications),
    interviews: structuredClone(interviews),
    offers: structuredClone(offers),
    notifications: structuredClone(notifications),
    assignments: structuredClone(assignments),
    sessionProfessionalId: null,
  };
}
